import confetti from "canvas-confetti";
import { GradeType, SeverityLevel, AnalysisResult } from "../types";

export function getSeverityColor(sev: SeverityLevel): { text: string; bg: string; border: string; glow: string } {
  switch (sev) {
    case "critical":
      return { text: "text-red-400", bg: "bg-red-500/10", border: "border-red-500/30", glow: "shadow-red-500/20" };
    case "high":
      return { text: "text-orange-400", bg: "bg-orange-500/10", border: "border-orange-500/30", glow: "shadow-orange-500/20" };
    case "medium":
      return { text: "text-amber-400", bg: "bg-amber-500/10", border: "border-amber-500/30", glow: "shadow-amber-500/20" };
    case "low":
      return { text: "text-sky-400", bg: "bg-sky-500/10", border: "border-sky-500/30", glow: "shadow-sky-500/20" };
    default:
      return { text: "text-slate-400", bg: "bg-slate-500/10", border: "border-slate-500/30", glow: "shadow-slate-500/20" };
  }
}

export function getGradeColor(grade: GradeType): { text: string; bg: string; border: string; stroke: string } {
  switch (grade) {
    case "A":
      return { text: "text-emerald-400", bg: "bg-emerald-500/10", border: "border-emerald-500/30", stroke: "#10B981" };
    case "B":
      return { text: "text-blue-400", bg: "bg-blue-500/10", border: "border-blue-500/30", stroke: "#3B82F6" };
    case "C":
      return { text: "text-amber-400", bg: "bg-amber-500/10", border: "border-amber-500/30", stroke: "#F59E0B" };
    case "D":
      return { text: "text-orange-400", bg: "bg-orange-500/10", border: "border-orange-500/30", stroke: "#F97316" };
    case "F":
      return { text: "text-red-400", bg: "bg-red-500/10", border: "border-red-500/30", stroke: "#EF4444" };
    default:
      return { text: "text-slate-400", bg: "bg-slate-500/10", border: "border-slate-500/30", stroke: "#64748B" };
  }
}

export function triggerConfetti(): void {
  confetti({
    particleCount: 80,
    spread: 70,
    origin: { y: 0.6 },
    colors: ["#6366F1", "#8B5CF6", "#22D3EE", "#10B981"],
  });
}

export function exportMarkdownReport(result: AnalysisResult, filename: string): string {
  const dateStr = new Date().toLocaleString();
  return `# CodeLens Review Report: ${filename}
Generated on: ${dateStr}

## Executive Summary
- **Overall Score**: ${result.score}/100 (Grade: ${result.grade})
- **Total Issues**: ${result.summary.total_issues}
- **Lines of Code**: ${result.summary.lines_of_code}
- **Maintainability Index**: ${result.metrics.maintainability_index}
- **Average Complexity**: ${result.metrics.avg_complexity}

### Subscores
- **Security**: ${result.subscores.security}/100
- **Reliability**: ${result.subscores.reliability}/100
- **Maintainability**: ${result.subscores.maintainability}/100

---

## Detected Issues

| Line | Severity | Category | Rule | Description | Suggestion |
| :--- | :--- | :--- | :--- | :--- | :--- |
${result.issues
  .map(
    (i) =>
      `| ${i.line} | **${i.severity.toUpperCase()}** | ${i.category} | ${i.title} | ${i.message.replace(/\|/g, "/")} | ${i.suggestion.replace(/\|/g, "/")} |`
  )
  .join("\n")}

---
*Report generated by CodeLens Static Analysis Engine.*
`;
}

export function downloadJsonFile(data: unknown, filename = "codelens-report.json"): void {
  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
